// =============================================================================
// string_set.h — СЕРЦЕ ЛАБОРАТОРНОЇ.
//
// Клас StringSet — «множина рядків» з умови: рядки з 1..15 рядкових латинських
// літер, операції додати / вилучити / перевірити + (варіант 2) усі паліндроми.
//
// Як усе влаштовано (коротко):
//   * Хеш-таблиця з методом ланцюгів (Лекція 1): масив head_ «голів» ланцюгів,
//     кожен ланцюг — однозв'язний список вузлів.
//   * Подвійний поліноміальний хеш (Лекція 3): h1 за модулем 1 000 000 123,
//     h2 за модулем 2^64. Разом колізія практично неможлива (~3·10^-17).
//   * Паліндроми: за той самий прохід рахуємо ще й хеш ОБЕРНЕНОГО рядка;
//     прямий == обернений -> паліндром (підтверджуємо посимвольно).
//
// Файл — «header-only»: увесь код класу тут, main.cpp просто робить #include.
// =============================================================================

// #pragma once — захист від повторного включення: якщо файл підключать двічі,
// компілятор обробить його лише один раз (інакше — помилка «клас оголошено двічі»).
#pragma once

// Стандартні бібліотеки, які використовуються нижче:
#include <algorithm>  // загальні алгоритми (про запас для std::sort тощо)
#include <cstdint>    // типи фіксованої ширини: uint8_t, uint32_t, uint64_t
#include <cstring>    // std::memcpy (копіювання байтів), std::memcmp (порівняння)
#include <random>     // std::mt19937_64 (генератор), std::random_device (ентропія)
#include <string>     // std::string — для результату palindromes()
#include <vector>     // std::vector — динамічний масив (head_, pool_)

class StringSet {
public:
    // Максимальна довжина рядка з умови. static const — одна константа на весь
    // клас (не зберігається в кожному об'єкті), відома на етапі компіляції,
    // тому нею можна задавати розміри масивів (див. Node::s, pw1_, pw2_).
    static const int MAX_LEN = 15;

    // -------------------------------------------------------------------------
    // КОНСТРУКТОР. Викликається один раз при створенні множини
    // (у main.cpp: `StringSet set(seed);`). Готує все для хешування.
    //
    // explicit — забороняє неявне перетворення числа в StringSet
    // (без нього `StringSet s = 7;` або `f(42)` для f(const StringSet&)
    // компілювалися б «тихо»; число — не множина, тож забороняємо).
    //
    // seed = 0 (значення за замовчуванням) -> основа p обирається випадково;
    // seed != 0 -> p завжди однакова (відтворюваність, використовують тести: -s).
    // -------------------------------------------------------------------------
    explicit StringSet(uint64_t seed = 0) {
        // Генератор псевдовипадкових чисел Мерсенна (64-бітний).
        // Тернарний оператор: якщо seed != 0 — стартуємо з нього,
        // інакше беремо 2×32 біти системної ентропії й склеюємо в 64 біти:
        // перше число — молодші 32 біти, друге зсунуте на 32 — старші, «^» (XOR) поєднує.
        // Примітка: у MinGW g++ 8.1 std::random_device НЕ випадковий (повертає
        // одні й ті самі числа), тому з цим компілятором p фактично однакова
        // між запусками. На коректність не впливає.
        std::mt19937_64 rng(seed ? seed : std::random_device{}() ^
                                          ((uint64_t)std::random_device{}() << 32));

        // Вибір основи p за правилами Лекції 3 («Вибір основи p»):
        //   * p > max(a_i) = 26 (коди літер 1..26),
        //   * p < M1,
        //   * p непарне -> НСД(p, 2^64) = 1.
        // 27 + (0 .. M1-29) дає діапазон 27 .. M1-2; після ++p максимум M1-1 < M1.
        uint64_t p = 27 + rng() % (M1 - 28);
        if (p % 2 == 0) ++p;

        // Наперед рахуємо степені p^0 .. p^14 за обома модулями, щоб hash()
        // лише брав їх з масиву, а не підносив до степеня щоразу.
        pw1_[0] = 1;
        pw2_[0] = 1;
        for (int i = 1; i < MAX_LEN; ++i) {
            // Приведення до uint64_t ОБОВ'ЯЗКОВЕ: два числа ~10^9 дають добуток
            // ~10^18, що переповнило б 32 біти. Потім % M1 і назад у 32 біти.
            pw1_[i] = (uint32_t)((uint64_t)pw1_[i - 1] * p % M1);
            // Для модуля 2^64 нічого робити не треба: uint64_t при переповненні
            // автоматично «загортається» за модулем 2^64 (гарантія стандарту C++).
            pw2_[i] = pw2_[i - 1] * p;
        }

        // Порожня таблиця: INIT_CAP = 16 ланцюгів, кожен = -1 («порожній»).
        // assign(кількість, значення) — задає розмір вектора і заповнює його.
        // Це НЕ передвиділення під усі дані: таблиця росте в grow() під час роботи.
        head_.assign(INIT_CAP, -1);
    }

    // -------------------------------------------------------------------------
    // ДОДАВАННЯ — операція «+».
    // Повертає true, якщо рядок реально додано, false — якщо він уже був
    // (множина не зберігає дублікатів; умова: «не гарантується, що він відсутній»).
    // main.cpp результат не використовує — це зручність (як у std::set::insert).
    // Час: Θ(L) хеш + O(1+α) пошук + O(L) копіювання/перевірка паліндрома.
    // -------------------------------------------------------------------------
    bool insert(const char* s, int len) {
        // 1) Прямий і обернений хеші за обома модулями — один прохід, Θ(L).
        Hash h = hash(s, len);

        // 2) Уже є? Тоді нічого не робимо (властивість множини). nullptr —
        //    попередник вузла нам тут не потрібен.
        if (find(s, len, h, nullptr) != -1) return false;

        // 3) Тримаємо коефіцієнт заповнення α = n / cap <= 1: якщо після
        //    вставки рядків стане більше, ніж ланцюгів, — подвоюємо таблицю.
        //    Завдяки цьому середня довжина ланцюга <= 1 -> операції O(1).
        if (size_ + 1 > head_.size()) grow();

        // 4) Беремо вузол для нового рядка:
        //    - якщо є вільний (після вилучення) — перевикористовуємо його
        //      (вільний список: free_ -> вузол -> next -> ...);
        //    - інакше додаємо новий у кінець пулу (emplace_back створює
        //      елемент прямо у векторі; вектор сам розширюється за потреби).
        int id;
        if (free_ != -1) {
            id = free_;
            free_ = pool_[id].next;
        } else {
            id = (int)pool_.size();
            pool_.emplace_back();
        }

        // 5) Заповнюємо вузол. Node& — посилання: змінюємо сам елемент пулу,
        //    а не копію. memcpy копіює len байтів рядка; '\0' в кінці робить
        //    з нього звичайний C-рядок (зручно для налагодження).
        Node& nd = pool_[id];
        std::memcpy(nd.s, s, len);
        nd.s[len] = '\0';
        nd.len = (uint8_t)len;
        nd.h1 = h.h1;  // зберігаємо хеші: потрібні для швидкого порівняння
        nd.h2 = h.h2;  // у find() і для перенесення у grow() без перерахунку

        // 6) ВАРІАНТ 2. Паліндром <=> рядок дорівнює своєму оберненому.
        //    Отже прямий хеш == оберненому — необхідна умова (Лекція 3).
        //    && обчислюється зліва направо і зупиняється на першому false:
        //    якщо хеші різні (майже завжди для не-паліндромів) — isPalindrome
        //    навіть не викликається; якщо рівні — підтверджуємо за O(L).
        //    Результат запам'ятовуємо: паліндромність рядка ніколи не зміниться.
        nd.pal = h.h1 == h.r1 && h.h2 == h.r2 && isPalindrome(s, len);

        // 7) Вставка на ПОЧАТОК ланцюга свого кошика — O(1)
        //    (CHAINED-HASH-INSERT з Лекції 1).
        size_t b = bucket(h.h1, h.h2);
        nd.next = head_[b];
        head_[b] = id;
        ++size_;
        return true;
    }

    // -------------------------------------------------------------------------
    // ВИЛУЧЕННЯ — операція «-».
    // Повертає true, якщо рядок був і його вилучено; false — якщо його не було
    // (умова: «не гарантується, що він є у множині»).
    // Список ОДНОзв'язний: вилучаємо за ключем, тож ланцюг однаково проходимо,
    // і попередника (prev) дізнаємося дорогою — двозв'язний список не потрібен.
    // Час: Θ(L) + O(1+α) + O(L) (memcmp при збігу у find).
    // -------------------------------------------------------------------------
    bool erase(const char* s, int len) {
        Hash h = hash(s, len);
        int prev;                          // сюди find() запише попередника
        int id = find(s, len, h, &prev);   // &prev — передаємо адресу змінної
        if (id == -1) return false;        // рядка немає — нічого не робимо

        // Вирізаємо вузол з ланцюга:
        //  - він перший (prev == -1) -> голова кошика тепер вказує на наступний;
        //  - він у середині -> попередник «перестрибує» через нього.
        if (prev == -1)
            head_[bucket(h.h1, h.h2)] = pool_[id].next;
        else
            pool_[prev].next = pool_[id].next;

        // Вузол не звільняємо з пам'яті, а кладемо у вільний список —
        // insert() перевикористає його. Так пам'ять не фрагментується.
        pool_[id].next = free_;
        free_ = id;
        --size_;
        return true;
    }

    // -------------------------------------------------------------------------
    // ПЕРЕВІРКА — операція «?». Просто пошук. const у кінці означає, що метод
    // не змінює об'єкт (його можна викликати й для const StringSet).
    // Час: Θ(L) + O(1+α) + O(L).
    // -------------------------------------------------------------------------
    bool contains(const char* s, int len) const {
        return find(s, len, hash(s, len), nullptr) != -1;
    }

    // -------------------------------------------------------------------------
    // ВАРІАНТ 2: УСІ ПАЛІНДРОМИ МНОЖИНИ. Викликається з main.cpp після «#».
    // Один прохід по всіх ланцюгах, беремо вузли з pal == true.
    // Нічого не хешуємо й не порівнюємо — ознака вже обчислена в insert().
    // Час: O(cap + n) = O(n), бо cap < 2n + 16.
    // -------------------------------------------------------------------------
    std::vector<std::string> palindromes() const {
        std::vector<std::string> res;
        for (int first : head_)                                  // кожен кошик
            for (int id = first; id != -1; id = pool_[id].next)  // кожен вузол ланцюга
                if (pool_[id].pal) res.emplace_back(pool_[id].s, pool_[id].len);
        return res;
    }

    // Кількість рядків у множині (n) і кількість кошиків (cap).
    // Виводяться з ключем -t у main.cpp (size=..., capacity=...).
    size_t size() const { return size_; }
    size_t capacity() const { return head_.size(); }

    // Пряма перевірка паліндрома: порівнюємо символи з двох кінців до середини.
    // Не більше L/2 = 7 порівнянь. static — метод не потребує об'єкта.
    static bool isPalindrome(const char* s, int len) {
        for (int i = 0, j = len - 1; i < j; ++i, --j)
            if (s[i] != s[j]) return false;
        return true;
    }

private:
    // Перший модуль (просте число з рекомендації Лекції 3). Другий модуль 2^64
    // явно не записаний — його «дає» переповнення uint64_t.
    static const uint32_t M1 = 1000000123;
    // Початкова кількість кошиків. Має бути степенем двійки: bucket() бере
    // x & (cap - 1), що дорівнює x % cap лише для степенів двійки.
    // Степінь двійки зберігається, бо grow() завжди множить розмір на 2.
    static const size_t INIT_CAP = 16;

    // Результат hash(): прямі (h) й обернені (r) хеші за обома модулями.
    struct Hash {
        uint32_t h1, r1;  // mod M1 — значення < 10^9, вміщується в 32 біти
        uint64_t h2, r2;  // mod 2^64 — повний 64-бітний тип
    };

    // Один збережений рядок = один вузол ланцюга.
    struct Node {
        char s[MAX_LEN + 1];  // символи рядка + '\0'
        uint8_t len;          // довжина 1..15 (вистачає 1 байта)
        bool pal;             // чи є паліндромом (обчислено один раз в insert)
        uint32_t h1;          // хеш mod M1
        uint64_t h2;          // хеш mod 2^64
        int next;             // індекс наступного вузла ланцюга (або вільного
                              // списку); -1 = кінець. Індекси замість вказівників:
                              // pool_ може переїхати в пам'яті при розширенні,
                              // а індекси лишаються правильними.
    };

    uint32_t pw1_[MAX_LEN];   // p^i mod M1, i = 0..14
    uint64_t pw2_[MAX_LEN];   // p^i mod 2^64
    std::vector<int> head_;   // голови ланцюгів: head_[b] = перший вузол кошика b або -1
    std::vector<Node> pool_;  // усі вузли; вилучені йдуть у вільний список
    int free_ = -1;           // голова вільного списку (-1 = вільних немає)
    size_t size_ = 0;         // n — скільки рядків зараз у множині

    // -------------------------------------------------------------------------
    // ПОЛІНОМІАЛЬНИЙ ХЕШ (Лекція 3), прямий і обернений, за ОДИН прохід, Θ(L):
    //   H = Σ a_i · p^i,         a_i = код i-го символу
    //   R = Σ a_{L-1-i} · p^i    (той самий хеш для оберненого рядка)
    // Код символу a_i = c - 'a' + 1 (1..26), а не 0..25: інакше 'a' мала б код 0
    // і рядки "a", "aa", "aaa" мали б однаковий хеш 0.
    // -------------------------------------------------------------------------
    Hash hash(const char* s, int len) const {
        uint64_t h1 = 0, r1 = 0, h2 = 0, r2 = 0;
        for (int i = 0; i < len; ++i) {
            uint64_t a = (uint64_t)(s[i] - 'a' + 1);            // i-й символ з початку
            uint64_t b = (uint64_t)(s[len - 1 - i] - 'a' + 1);  // i-й символ з кінця
            h1 += a * pw1_[i];
            r1 += b * pw1_[i];
            h2 += a * pw2_[i];  // mod 2^64 — автоматично
            r2 += b * pw2_[i];
        }
        // Для M1 беремо модуль один раз у кінці: кожен доданок < 27·10^9,
        // 15 доданків < 4·10^11 — сума точно вміщується в uint64_t.
        return {(uint32_t)(h1 % M1), (uint32_t)(r1 % M1), h2, r2};
    }

    // -------------------------------------------------------------------------
    // НОМЕР КОШИКА з двох хешів, O(1). Змішуємо h1 і h2 (множення на «золоте»
    // число 0x9E37... розкидає біти), складаємо старшу й молодшу половини (^ >> 32)
    // і беремо молодші біти: x & (cap - 1) == x % cap, бо cap — степінь двійки.
    // -------------------------------------------------------------------------
    size_t bucket(uint32_t h1, uint64_t h2) const {
        uint64_t x = h2 ^ ((uint64_t)h1 * 0x9E3779B97F4A7C15ULL);
        x ^= x >> 32;
        return (size_t)(x & (head_.size() - 1));
    }

    // -------------------------------------------------------------------------
    // ПОШУК У ЛАНЦЮГУ (CHAINED-HASH-SEARCH з Лекції 1). Спільний для +, -, ?.
    // Повертає індекс вузла або -1. Якщо prev != nullptr — записує туди
    // попередника знайденого вузла (потрібно для erase()).
    //
    // Порядок перевірок у if важливий (&& зупиняється на першому false):
    //   спершу дешеві O(1) — h2, h1, довжина; лише при повному збігу —
    //   memcmp за O(L), що виключає хибне спрацювання навіть при колізії хешів.
    // Час: O(1 + α) вузлів у ланцюгу + O(L) на memcmp знайденого.
    // -------------------------------------------------------------------------
    int find(const char* s, int len, const Hash& h, int* prev) const {
        int pr = -1;
        for (int id = head_[bucket(h.h1, h.h2)]; id != -1; pr = id, id = pool_[id].next) {
            const Node& nd = pool_[id];
            if (nd.h2 == h.h2 && nd.h1 == h.h1 && nd.len == len &&
                std::memcmp(nd.s, s, len) == 0) {
                if (prev) *prev = pr;
                return id;
            }
        }
        return -1;
    }

    // -------------------------------------------------------------------------
    // ПОДВОЄННЯ ТАБЛИЦІ (rehash). Викликається з insert(), коли n > cap.
    // Новий розмір = старий · 2 (16 -> 32 -> 64 -> ...), тож завжди степінь двійки.
    // Кожен вузол переносимо в новий кошик. Хеші НЕ перераховуємо — вони
    // збережені у вузлі (h1, h2), тому перенесення O(1) на вузол.
    // Одне подвоєння — O(n + cap), але вони рідкі: сума всіх < 2n,
    // тобто O(1) амортизовано на одну вставку.
    // -------------------------------------------------------------------------
    void grow() {
        std::vector<int> old;
        old.swap(head_);                     // старі голови -> old, head_ порожній (O(1))
        head_.assign(old.size() * 2, -1);    // нова таблиця вдвічі більша
        for (int first : old) {
            for (int id = first; id != -1;) {
                int nx = pool_[id].next;     // запам'ятати наступного ДО зміни next
                size_t b = bucket(pool_[id].h1, pool_[id].h2);
                pool_[id].next = head_[b];   // вставка на початок нового ланцюга
                head_[b] = id;
                id = nx;
            }
        }
    }
};
