// =============================================================================
// gen.cpp — ГЕНЕРАТОР ТЕСТІВ. Збирається в gen.exe.
// Умова: «згенерувати не менше 10^4 - 10^5» рядків. Програма пише у stdout
// текстовий файл того ж формату, що читає lab.exe ("+ word" ... "#").
// Нічого не «експортує»: результат перенаправляють у файл: gen.exe ... > file.txt
//
// Використання: gen N seed [add del ask] [pool] [pal]
//   N           — кількість операцій (рядків файлу), <= 10^6
//   seed        — зерно генератора: однакове зерно -> однаковий файл
//   add del ask — відносні ваги операцій "+", "-", "?"      (типово 50 20 30)
//   pool        — кількість різних слів, з яких беруться операції (типово N/3)
//   pal         — відсоток спеціально побудованих паліндромів у пулі (типово 10)
// Аргументи позиційні: необов'язкові можна пропускати лише з кінця;
// три ваги задаються разом або жодної.
//
// Навіщо пул: слова беруться з обмеженого набору, тому бувають повторні
// додавання, вилучення відсутніх рядків і відповіді як "yes", так і "no"
// (усі випадки з умови). Навіщо паліндроми «вручну»: випадковий рядок довжини
// >= 6 є паліндромом з імовірністю < 1/17 000 — інакше довгих паліндромів не було б.
// =============================================================================

#include <cstdio>
#include <cstdlib>   // std::atoll, std::atoi, std::strtoull — рядок -> число
#include <random>    // std::mt19937_64
#include <string>
#include <vector>

int main(int argc, char** argv) {
    // --- 1. Аргументи ---------------------------------------------------------
    // N і seed обов'язкові; без них — підказка і вихід з кодом помилки 1.
    if (argc < 3) {
        std::fprintf(stderr, "usage: gen N seed [add del ask] [pool] [pal]\n");
        return 1;
    }
    long long n = std::atoll(argv[1]);
    unsigned long long seed = std::strtoull(argv[2], nullptr, 10);
    int wAdd = 50, wDel = 20, wAsk = 30;  // значення за замовчуванням
    if (argc >= 6) {                      // ваги — лише якщо задані всі три
        wAdd = std::atoi(argv[3]);
        wDel = std::atoi(argv[4]);
        wAsk = std::atoi(argv[5]);
    }
    long long pool = argc >= 7 ? std::atoll(argv[6]) : n / 3;
    int palPct = argc >= 8 ? std::atoi(argv[7]) : 10;
    if (pool < 1) pool = 1;  // хоча б одне слово (напр. при N < 3)
    if (wAdd + wDel + wAsk <= 0) {
        std::fprintf(stderr, "operation weights must not all be zero\n");
        return 1;
    }

    // --- 2. Генератор випадкових чисел ----------------------------------------
    // Псевдовипадковий: уся послідовність визначається seed. Звідси
    // відтворюваність: той самий seed -> ті самі довжини, літери, операції.
    std::mt19937_64 rng(seed);
    // Лямбда-функції ([&] — бачать змінні навколо, зокрема rng):
    //   rnd(k)   — випадкове ціле 0..k-1;
    //   letter() — випадкова літера 'a'..'z'.
    auto rnd = [&](long long k) { return (long long)(rng() % (unsigned long long)k); };
    auto letter = [&]() { return (char)('a' + rnd(26)); };

    // --- 3. Пул слів ----------------------------------------------------------
    std::vector<std::string> words(pool);
    for (std::string& w : words) {       // & — змінюємо саме слово у векторі
        int len = 1 + (int)rnd(15);      // довжина 1..15
        w.resize(len);
        if (rnd(100) < palPct) {
            // Паліндром: одна випадкова літера записується в дзеркальні позиції
            // i та len-1-i. Для непарної довжини центр (i == len-1-i) — довільний.
            for (int i = 0; i < (len + 1) / 2; ++i) w[i] = w[len - 1 - i] = letter();
        } else {
            for (char& c : w) c = letter();  // звичайний випадковий рядок
        }
    }

    // --- 4. N операцій ----------------------------------------------------------
    // Увесь файл спершу збирається в один рядок у пам'яті (reserve — виділяє
    // місце наперед, ~12 байт на рядок), потім записується одним fwrite: швидко.
    std::string out;
    out.reserve((size_t)n * 12 + 4);
    int total = wAdd + wDel + wAsk;
    for (long long i = 0; i < n; ++i) {
        // Випадкове r у 0..total-1 обирає операцію пропорційно вагам:
        // [0, wAdd) -> '+', [wAdd, wAdd+wDel) -> '-', решта -> '?'.
        int r = (int)rnd(total);
        out += r < wAdd ? '+' : r < wAdd + wDel ? '-' : '?';
        out += ' ';
        out += words[rnd(pool)];  // випадкове слово з пулу
        out += '\n';
    }
    out += "#\n";  // ознака кінця вхідних даних (умова)
    std::fwrite(out.data(), 1, out.size(), stdout);
    return 0;
}
